// Imports CJdropshipping products into the store.
//
//   CJ_API_KEY=... node scripts/cj-import.mjs --search "led menorah"   list US-warehouse matches
//   CJ_API_KEY=... node scripts/cj-import.mjs                          import everything in cj-picks.json
//
// Writes cj-products.js (read by catalog.js) and downloads product photos into images/cj/.
// Prints cost, CJ shipping to the sample ZIP, retail price and margin for each variant, so a principal
// can check the numbers before pushing.
import fs from "node:fs";
import { cjToken, cjPickShipping } from "../lib/cj.js";
import { OCCASIONS } from "../catalog.js";

const BASE = "https://developers.cjdropshipping.com/api2.0/v1";
const root = new URL("../", import.meta.url).pathname;
const key = process.env.CJ_API_KEY;
if (!key) { console.error("Set CJ_API_KEY (CJ → Authorization → API → API key)."); process.exit(1); }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const token = await cjToken(key);
async function get(path) {
  await sleep(1100); // CJ allows about one call per second
  const r = await fetch(BASE + path, { headers: { "CJ-Access-Token": token } });
  const j = await r.json();
  if (!(j.result === true || j.code === 200)) throw new Error(`${path}: ${j.code} ${j.message}`);
  return j.data;
}

if (process.argv.includes("--search")) {
  const q = process.argv[process.argv.indexOf("--search") + 1];
  const d = await get(`/product/listV2?keyWord=${encodeURIComponent(q)}&countryCode=US&size=40&page=1`);
  const list = (d.content || []).flatMap((c) => c.productList || []);
  if (!list.length) console.log("No US-warehouse matches.");
  for (const p of list) console.log(`${p.id}  $${p.sellPrice}  stock ${p.warehouseInventoryNum ?? "?"}  ${p.nameEn}`);
  process.exit(0);
}

const cfg = JSON.parse(fs.readFileSync(root + "scripts/cj-picks.json", "utf8"));
const occ = new Set(OCCASIONS.map((o) => o.id));
const imgs = (set) => (Array.isArray(set) ? set : String(set || "").replace(/[\[\]"]/g, "").split(",")).map((s) => s.trim()).filter(Boolean);
async function download(url, rel) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`download ${r.status} ${url}`);
  fs.mkdirSync(root + rel.replace(/\/[^/]+$/, ""), { recursive: true });
  fs.writeFileSync(root + rel, Buffer.from(await r.arrayBuffer()));
  return rel;
}
const retail = (cost, pick, opt) =>
  typeof pick.price === "number" ? pick.price : pick.price && pick.price[opt] != null ? pick.price[opt] : Math.ceil(cost * (cfg.markup || 2.5)) - 0.01;

const out = [];
for (const pick of cfg.picks) {
  if (!occ.has(pick.occasion)) { console.log(`! ${pick.id}: unknown occasion "${pick.occasion}"`); continue; }
  const d = await get(`/product/query?pid=${encodeURIComponent(pick.pid)}&countryCode=US`);
  const vars = (d.variants || []).filter((v) => !pick.variants || pick.variants.includes(v.variantKey));
  if (!vars.length) { console.log(`! ${pick.id}: no variants in stock in a US warehouse`); continue; }
  const single = vars.length === 1;
  const options = vars.map((v) => (single ? "Standard" : v.variantKey || v.variantNameEn));
  const vids = {}, prices = {}, cost = {}, optionPhotos = {};
  const photos = [];
  for (const [i, u] of imgs(d.productImageSet).slice(0, 5).entries()) photos.push(await download(u, `images/cj/${pick.id}/${i + 1}.jpg`).catch(() => null));
  for (const [i, v] of vars.entries()) {
    const o = options[i];
    vids[o] = v.vid; cost[o] = Number(v.variantSellPrice); prices[o] = retail(cost[o], pick, o);
    if (v.variantImage && !single) optionPhotos[o] = await download(v.variantImage, `images/cj/${pick.id}/v-${i + 1}.jpg`).catch(() => null);
  }
  let ship = null;
  try { await sleep(1100); ship = await cjPickShipping(token, cfg.sampleZip || "38103", [{ vid: vars[0].vid, quantity: 1 }]); } catch (e) { console.log(`! ${pick.id}: ${e.message}`); }
  out.push({
    id: pick.id, supplier: "cj", type: "cj", occasion: pick.occasion, name: pick.name, blurb: pick.blurb,
    colors: ["std"], options, prices, price: Math.min(...Object.values(prices)), vids, cost,
    photos: photos.filter(Boolean), optionPhotos, cjPid: d.pid || pick.pid,
    spec: pick.spec || "Ships from a US warehouse.", ...(pick.optionLabel ? { optionLabel: pick.optionLabel } : { optionLabel: "Option" }),
  });
  for (const o of options) {
    const s = ship ? Number(ship.logisticPrice) : NaN, m = prices[o] - cost[o] - (s || 0);
    console.log(`${pick.id} [${o}]  cost $${cost[o].toFixed(2)}  CJ ship $${isNaN(s) ? "?" : s.toFixed(2)} (${ship ? `${ship.logisticName}, ${ship.logisticAging} days` : "no route"})  price $${prices[o].toFixed(2)}  margin before fees $${m.toFixed(2)}`);
  }
}
fs.writeFileSync(root + "cj-products.js",
  `// Products fulfilled by CJdropshipping from its US warehouses.\n// Generated by scripts/cj-import.mjs from scripts/cj-picks.json on ${new Date().toISOString().slice(0, 10)}. Edit the picks file, not this one.\nexport const CJ_PRODUCTS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`\n${out.length} CJ products written to cj-products.js. Commit cj-products.js and images/cj/, then push.`);
